import 'package:equatable/equatable.dart';
import '../../domain/entities/storage_item.dart';
import '../../domain/entities/storage_enums.dart';

class StorageItemDto extends Equatable {
  const StorageItemDto({
    required this.id,
    required this.name,
    required this.kind,
    required this.date,
    this.dataUrl,
    this.url,
    this.sizeLabel = '',
    this.authorId = '',
    this.authorName = '',
    this.taskId,
    this.taskDisplayId = '',
    this.taskTitle = '',
    this.messageId,
    this.favorited = false,
    this.mimeType = '',
  });
  final String id,
      name,
      sizeLabel,
      authorId,
      authorName,
      taskDisplayId,
      taskTitle,
      mimeType;
  final StorageFileKind kind;
  final DateTime date;
  final String? dataUrl, url, taskId, messageId;
  final bool favorited;
  factory StorageItemDto.fromJson(Map<String, dynamic> json) => StorageItemDto(
    id: json['id']?.toString() ?? '',
    name: json['name']?.toString() ?? '',
    kind: StorageFileKind.values.firstWhere(
      (e) => e.name == json['kind'],
      orElse: () => StorageFileKind.other,
    ),
    date:
        DateTime.tryParse(json['date']?.toString() ?? '') ??
        DateTime.fromMillisecondsSinceEpoch(0),
    dataUrl: json['dataUrl'] as String?,
    url: json['url'] as String?,
    sizeLabel: json['sizeLabel']?.toString() ?? '',
    authorId: json['authorId']?.toString() ?? '',
    authorName: json['authorName']?.toString() ?? '',
    taskId: json['taskId'] as String?,
    taskDisplayId: json['taskDisplayId']?.toString() ?? '',
    taskTitle: json['taskTitle']?.toString() ?? '',
    messageId: json['messageId'] as String?,
    favorited: json['favorited'] == true,
    mimeType: json['mimeType']?.toString() ?? '',
  );
  Map<String, dynamic> toJson() => {
    'id': id,
    'name': name,
    'kind': kind.name,
    'date': date.toIso8601String(),
    'dataUrl': dataUrl,
    'url': url,
    'sizeLabel': sizeLabel,
    'authorId': authorId,
    'authorName': authorName,
    'taskId': taskId,
    'taskDisplayId': taskDisplayId,
    'taskTitle': taskTitle,
    'messageId': messageId,
    'favorited': favorited,
    'mimeType': mimeType,
  };
  StorageItemDto copyWith({
    String? id,
    String? name,
    StorageFileKind? kind,
    DateTime? date,
    String? dataUrl,
    String? url,
    String? sizeLabel,
    String? authorId,
    String? authorName,
    String? taskId,
    String? taskDisplayId,
    String? taskTitle,
    String? messageId,
    bool? favorited,
    String? mimeType,
  }) => StorageItemDto(
    id: id ?? this.id,
    name: name ?? this.name,
    kind: kind ?? this.kind,
    date: date ?? this.date,
    dataUrl: dataUrl ?? this.dataUrl,
    url: url ?? this.url,
    sizeLabel: sizeLabel ?? this.sizeLabel,
    authorId: authorId ?? this.authorId,
    authorName: authorName ?? this.authorName,
    taskId: taskId ?? this.taskId,
    taskDisplayId: taskDisplayId ?? this.taskDisplayId,
    taskTitle: taskTitle ?? this.taskTitle,
    messageId: messageId ?? this.messageId,
    favorited: favorited ?? this.favorited,
    mimeType: mimeType ?? this.mimeType,
  );
  factory StorageItemDto.fromEntity(StorageItem entity) => StorageItemDto(
    id: entity.id,
    name: entity.name,
    kind: entity.kind,
    date: entity.date,
    dataUrl: entity.dataUrl,
    url: entity.url,
    sizeLabel: entity.sizeLabel,
    authorId: entity.authorId,
    authorName: entity.authorName,
    taskId: entity.taskId,
    taskDisplayId: entity.taskDisplayId,
    taskTitle: entity.taskTitle,
    messageId: entity.messageId,
    favorited: entity.favorited,
    mimeType: entity.mimeType,
  );
  StorageItem toEntity() => StorageItem(
    id: id,
    name: name,
    kind: kind,
    date: date,
    dataUrl: dataUrl,
    url: url,
    sizeLabel: sizeLabel,
    authorId: authorId,
    authorName: authorName,
    taskId: taskId,
    taskDisplayId: taskDisplayId,
    taskTitle: taskTitle,
    messageId: messageId,
    favorited: favorited,
    mimeType: mimeType,
  );
  @override
  List<Object?> get props => [
    id,
    name,
    kind,
    date,
    dataUrl,
    url,
    sizeLabel,
    authorId,
    authorName,
    taskId,
    taskDisplayId,
    taskTitle,
    messageId,
    favorited,
    mimeType,
  ];
}
